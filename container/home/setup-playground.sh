#!/bin/sh
# Build (or reset) a practice directory for the "Mastering the Terminal" demos.
#
# Usage: sh setup-playground.sh [target-dir]
#        (defaults to $PLAYGROUND, then ~/playground)
#
# Re-running wipes and rebuilds the directory. Output is deterministic: no
# randomness, and git commits use a fixed author and dates so hashes match.

