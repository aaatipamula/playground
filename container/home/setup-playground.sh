import http from "node:http";
import { slugify } from "../utils/strings.js";

const tasks = [
  { id: 1, title: "Learn the terminal", due: "2026-10-01", done: true },
  { id: 2, title: "Configure zsh", due: "2026-10-20", done: false },
  { id: 3, title: "Try lazygit", due: null, done: false },
];

export function startServer(port = 8080) {
  const server = http.createServer((req, res) => {
    if (req.url === "/tasks") {
      res.setHeader("Content-Type", "application/json");
      res.end(JSON.stringify(tasks.map((t) => ({ ...t, slug: slugify(t.title) }))));
      return;
    }
    // TODO: return a proper 404 page
    res.statusCode = 404;
    res.end("not found");
  });
  server.listen(port, () => console.log(`listening on http://localhost:${port}`));
  return server;
}
