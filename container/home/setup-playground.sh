cat > scripts/log-writer.sh <<'EOF'
#!/bin/sh
# Appends a line to ../logs/live.log every second. Pair with: tail -f logs/live.log
dir="$(cd "$(dirname "$0")/.." && pwd)"
out="$dir/logs/live.log"
n="${1:-300}"
i=1
while [ "$i" -le "$n" ]; do
  case $((i % 7)) in
    0) lvl=ERROR msg="payment service unreachable" ;;
    3) lvl=WARN  msg="response took 1.8s" ;;
    *) lvl=INFO  msg="handled request #$i" ;;
  esac
  echo "$(date '+%Y-%m-%d %H:%M:%S') [$lvl] $msg" >> "$out"
  sleep 1
  i=$((i + 1))
done
EOF

